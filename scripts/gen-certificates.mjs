// Generates lib/certificates.ts from the certificate files in public/certificates/.
// Each file is named after an award `key` (see lib/awards.ts); the Awards page
// shows a "View Certificate" button linking to whichever file is present.
//
// Accepts PDFs and common image formats, so any certificate — however it was
// issued — just works once dropped in. Runs automatically via the `predev` /
// `prebuild` npm lifecycle scripts. Committed to git as a normal source file —
// regenerated, never hand-edited.
import { readdirSync, writeFileSync, existsSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { dirname, join, extname } from "node:path";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const certDir = join(root, "public", "certificates");
const outFile = join(root, "lib", "certificates.ts");

// Accepted extensions in precedence order (if a key has more than one file,
// the earliest listed format wins).
const EXTS = [".pdf", ".jpg", ".jpeg", ".png"];

const files = existsSync(certDir) ? readdirSync(certDir) : [];
const byKey = {};
for (const ext of EXTS) {
  for (const f of files) {
    if (extname(f).toLowerCase() !== ext) continue;
    const key = f.slice(0, -ext.length);
    if (!(key in byKey)) byKey[key] = f; // keep the highest-precedence format
  }
}

const map = Object.fromEntries(
  Object.keys(byKey)
    .sort()
    .map((k) => [k, byKey[k]])
);

const out = `// AUTO-GENERATED by scripts/gen-certificates.mjs — do not edit by hand.
// Maps each award key to its certificate file in public/certificates/.
// Regenerated on every \`npm run dev\` and \`npm run build\`.
export const certificateFiles: Record<string, string> = ${JSON.stringify(map, null, 2)};
`;

writeFileSync(outFile, out);
const entries = Object.entries(map);
console.log(
  `[gen-certificates] ${entries.length} certificate(s): ${
    entries.map(([k, f]) => `${k}→${f}`).join(", ") || "(none)"
  }`
);
