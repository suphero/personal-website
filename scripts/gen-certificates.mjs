// Generates lib/certificates.ts from the PDFs present in public/certificates/.
// Each PDF is named after an award `key` (see lib/awards.ts); the Awards page
// shows a "View Certificate" button for every key listed here.
//
// Runs automatically via the `predev` / `prebuild` npm lifecycle scripts, so the
// manifest is refreshed before every `next dev` and `next build`. Committed to
// git as a normal source file — regenerated, never hand-edited.
import { readdirSync, writeFileSync, existsSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { dirname, join } from "node:path";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const certDir = join(root, "public", "certificates");
const outFile = join(root, "lib", "certificates.ts");

const keys = existsSync(certDir)
  ? readdirSync(certDir)
      .filter((f) => f.toLowerCase().endsWith(".pdf"))
      .map((f) => f.slice(0, -".pdf".length))
      .sort()
  : [];

const out = `// AUTO-GENERATED by scripts/gen-certificates.mjs — do not edit by hand.
// Award keys that have a certificate PDF in public/certificates/.
// Regenerated on every \`npm run dev\` and \`npm run build\`.
export const certificateKeys: readonly string[] = ${JSON.stringify(keys, null, 2)};
`;

writeFileSync(outFile, out);
console.log(
  `[gen-certificates] ${keys.length} certificate(s): ${keys.join(", ") || "(none)"}`
);
